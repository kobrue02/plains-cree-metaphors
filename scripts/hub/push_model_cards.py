"""
Push model cards to the HuggingFace Hub for all trained checkpoints.

Two ways entries get built:
  - Hand-written `summary` + `details` (teacher / baseline figurative classifiers —
    one-off runs that don't come out of pipeline.py).
  - `stage` + `stage_kwargs` (tlm / clkd / calibrated) — text is generated by
    `render_stage_card()` from the same run parameters pipeline.py uses, so the
    wording stays in sync with how the checkpoint was actually produced.

`push_card_for()` is imported directly by pipeline.py and called at the end of
each stage that pushes to the Hub, so new checkpoints get a card without a
separate manual step. Run this file directly to (re)push cards for everything,
e.g. after adding a new ablation condition or if a push failed mid-job:

  python scripts/hub/push_model_cards.py
  python scripts/hub/push_model_cards.py --repo KonradBRG/xlm-mlm-abl-full-plains-cree-en-calibrated

Requires: huggingface-cli login (or HF_TOKEN env var set)
"""

