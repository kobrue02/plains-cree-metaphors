def make_card(m: dict) -> ModelCard:
    language = m.get("language", LANGUAGE)
    stage    = m.get("stage")
    tags     = m.get("tags") or STAGE_TAGS.get(stage, [])
    task     = m.get("task") or STAGE_PIPELINE_TAG.get(stage, "text-classification")
    repo_name = m["repo_id"].split("/")[-1]

    eval_results = eval_results_for(m["experiment_name"]) if m.get("experiment_name") else None

    card_data = ModelCardData(
        language      = language if isinstance(language, list) else [language],
        license       = "cc-by-4.0",
        base_model    = m["base_model"],
        tags          = tags,
        pipeline_tag  = task,
        eval_results  = eval_results,
        model_name    = repo_name if eval_results else None,
    )

    if "summary" in m and "details" in m:
        summary, details = m["summary"], m["details"]
    else:
        summary, details = render_stage_card(stage, m["base_model"], **m.get("stage_kwargs", {}))

    results_section = ""
    if eval_results:
        rows = "\n".join(f"| {r.metric_name} | {r.metric_value} |" for r in eval_results)
        results_section = f"""
## Results

Evaluated on a held-out split of {eval_results[0].dataset_name}.

| Metric | Value |
|---|---|
{rows}
"""

    content = f"""\
---
{ card_data.to_yaml() }
---

# { repo_name }

{ summary }

{ details }
{ results_section }
{ CITATION_SECTION }

{ DATA_SECTION }
"""
    return ModelCard(content)


def push_card_for(repo_id: str, stage: str, base_model: str, **stage_kwargs) -> None:
    """Called by pipeline.py right after it pushes a checkpoint, so cards stay
    current without a manual step. Never raises — a failure here shouldn't fail
    an otherwise-successful job."""
    api = HfApi()
    try:
        api.repo_info(repo_id=repo_id, repo_type="model")
        card = make_card(dict(repo_id=repo_id, base_model=base_model, stage=stage, stage_kwargs=stage_kwargs))
        card.push_to_hub(repo_id)
        print(f"[hub] card pushed → {repo_id}")
    except Exception as exc:
        print(f"[hub] card push failed for {repo_id} — {exc}")


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--repo", default=None, help="Only push the card for this repo_id (default: all)")
    args = p.parse_args()

    api = HfApi()
    models = MODELS if args.repo is None else [m for m in MODELS if m["repo_id"] == args.repo]
    if not models:
        sys.exit(f"No entry for repo '{args.repo}' in MODELS")

    for m in models:
        repo = m["repo_id"]
        try:
            api.repo_info(repo_id=repo, repo_type="model")
            card = make_card(m)
            card.push_to_hub(repo)
            print(f"✓  {repo}")
        except Exception as exc:
            print(f"✗  {repo}  — {exc}")
