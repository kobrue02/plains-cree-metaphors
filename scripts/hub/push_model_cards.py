def render_stage_card(stage: str, base_model: str, **kw) -> tuple[str, str]:
    """Return (summary, details-markdown) for a pipeline-produced checkpoint.

    kw (all optional, matching pipeline.py's CLI args for that stage):
      tlm:        epochs, learning_rate, batch_size, max_length,
                  warm_start (mono-MLM checkpoint id, if used),
                  contrastive_alpha, contrastive_temperature
      clkd:       student_base, teacher, freeze_n_layers, temperature, epochs, learning_rate
      calibrated: student_base, literal_ratio, epochs, learning_rate, ablation_note
    """
    if stage == "tlm":
        warm_note = (
            f"\nWarm-started from a monolingual Cree MLM checkpoint (`{kw['warm_start']}`) "
            f"before cross-lingual TLM fine-tuning." if kw.get("warm_start") else ""
        )
        alpha = kw.get("contrastive_alpha") or 0.0
        contrastive_note = (
            f"\nTrained jointly with an InfoNCE alignment loss (alpha={alpha}, "
            f"temperature={kw.get('contrastive_temperature', 0.05)}) that explicitly pulls "
            f"Cree and English sentence representations together." if alpha else ""
        )
        summary = (
            f"{base_model} fine-tuned with the Translation Language Modeling (TLM) objective "
            f"on a Plains Cree–English parallel corpus."
        )
        details = f"""\
## Training

Fine-tuned using the TLM objective introduced in [Lample & Conneau (2019)](https://arxiv.org/abs/1901.07291).
Cree–English sentence pairs are concatenated and masked jointly, encouraging the model to use cross-lingual context when predicting masked tokens.{warm_note}{contrastive_note}

**Training data:** Bloomfield (1934) Plains Cree texts (scraped and sentence-aligned) + EdTeKLA parallel corpus (~9,000 sentence pairs total)
**Epochs:** {kw.get('epochs', 15)} | **Batch size:** {kw.get('batch_size', 16)} | **Max length:** {kw.get('max_length', 256)}
**Hardware:** 1× NVIDIA A100 40 GB

## Intended use

This checkpoint serves as the student encoder foundation for Cross-Lingual Knowledge Distillation (CLKD) of figurative language classifiers into Plains Cree.
"""
        return summary, details

    if stage == "clkd":
        teacher     = kw.get("teacher", TEACHER)
        student     = kw.get("student_base", base_model)
        freeze      = kw.get("freeze_n_layers", 0)
        freeze_note = (
            f"Layers 0–{freeze - 1} frozen to preserve cross-lingual alignment from TLM; "
            f"remaining layers + classification head trained."
            if freeze else "All layers trainable."
        )
        warm_note = "" if kw.get("tlm_warmup", student != base_model) else " (no TLM warmup)"
        summary = (
            f"{base_model} adapted for Plains Cree figurative language detection via "
            f"Cross-Lingual Knowledge Distillation (CLKD){warm_note}."
        )
        details = f"""\
## Method

Inspired by [Cross-Lingual Knowledge Distillation (ACL 2023)](https://aclanthology.org/2023.findings-acl.885/).

**CLKD pipeline:**
1. Teacher: `{teacher}` (frozen, English)
2. Student base: `{student}`
3. {freeze_note}

The teacher predicts soft label distributions on English translations of Plains Cree sentences.
The student is trained to match these distributions on the Cree side via KL divergence.

**Training data:** ~9,000 Cree–English parallel sentence pairs
**Temperature:** {kw.get('temperature', 2.0)} | **Epochs:** {kw.get('epochs', 10)} | **Hardware:** 1× NVIDIA A100 40 GB

**Labels:** `literal` (0), `idiom` (1), `metaphor` (2), `simile` (3)
"""
        return summary, details

    if stage == "calibrated":
        student    = kw.get("student_base", base_model)
        abl_note   = f"\n**Ablation condition:** {kw['ablation_note']}\n" if kw.get("ablation_note") else ""
        summary = (
            f"{base_model} calibrated on DeepSeek-annotated Bloomfield Plains Cree sentences "
            f"for figurative language detection."
        )
        details = f"""\
## Training

Low-LR calibration of a CLKD checkpoint on gold/silver Bloomfield validation data, held out and \
evaluated against the 219 footnote-verified gold sentences.
{abl_note}
**Base checkpoint:** `{student}`
**Literal : figurative ratio:** {kw.get('literal_ratio', 3)}:1 | **Epochs:** {kw.get('epochs', 10)} | **Learning rate:** {kw.get('learning_rate', 5e-6)}
**Hardware:** 1× NVIDIA A100 40 GB

**Labels:** `literal` (0), `idiom` (1), `metaphor` (2), `simile` (3)

## Intended use

Final deployed checkpoint for figurative language detection in Plains Cree.
"""
        return summary, details

    raise ValueError(f"No card template for stage '{stage}'")


